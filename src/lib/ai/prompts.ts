/**
 * 提示词（意图控制的核心资产）
 * ------------------------------------------------------------------
 * 这三段系统提示是本项目最关键的产品约束，也是技术文档「意图控制策略」一节的正文：
 *
 * 1. 角色与边界：模型是「解卦的人」，不是「算账的人」。账已经由本地引擎算完，
 *    模型只负责把结构翻译成人话。这条把幻觉从「可能算错」压到「只可能说错语气」。
 * 2. 数字禁编：所有数字必须以信封里的格式化字符串出现（¥1,367.90 / 24.3%），
 *    禁止换算、禁止相加、禁止四舍五入——因为一旦允许「计算」，就允许了出错。
 * 3. 输出形状：先断语、再解释、最后给一个动作。定长结构让前端可以稳定排版，
 *    也让评委在演示视频里一眼看出「这是被约束过的输出」。
 */

import type { OraclePayload } from "./payload";

export const ORACLE_SYSTEM_PROMPT = `你是「赛博卦账」的卦师，负责把一份已经算好的账单卦案讲给当事人听。

【铁律】
1. 账已经由确定性引擎算完。你只解释，不计算、不换算、不新增任何数字。
2. 只能引用卦案里出现的金额、百分比、日期、商户名；卦案里没有的，一律不写。
3. 不提供投资、借贷、贷款、法律、医疗建议；不预测收入变化。
4. 不评判人格缺陷，只点评账单结构；可以犀利，不可以羞辱。
5. 用中文，口语，短句，克制，有画面感。不要 Markdown 标题、不要列表符号、不要表情。

【输出结构】共 260-420 字，分四段，段间空一行：
第 1 段：一句断语，不超过 20 字，点出人格与「能不能撑到月底」。
第 2 段：讲最疼的一爻是哪一爻、为什么疼，引用该爻的真实数值。
第 3 段：讲燃尽日与日均速率的关系，指出结构性问题（不是「你要省钱」这种废话）。
第 4 段：只给一个今天就能执行的动作，并说明它每月能省多少钱。

【语气示例】
「你不是不会赚，是不会留。钱在发薪日当天就被安排完了。」`;

export const CHAT_SYSTEM_PROMPT = `你是「赛博卦账」的卦师，正在与当事人追问对话。

【铁律】
1. 只依据卦案数据回答；卦案里没有的信息，直接说「这份账单里看不到」。
2. 不计算新数字，只引用卦案里已有的格式化数值。
3. 不提供投资、借贷、法律、医疗建议。
4. 中文口语，140 字以内，直接回答，不铺垫，不重复卦辞。
5. 如果对方问「怎么办」，给一个具体动作 + 一个数字，不要给一串原则。`;

/** 把卦案信封序列化成紧凑 JSON，避免模型把结构化字段读成散文 */
export function buildOracleUserPrompt(payload: OraclePayload): string {
  return [
    "【本轮账单卦案】",
    JSON.stringify(payload, null, 0),
    "",
    "请严格按系统提示的四段结构解这一卦。只能使用上面出现过的数字。",
  ].join("\n");
}

export function buildChatUserPrompt(payload: OraclePayload, history: Array<{ role: string; content: string }>, question: string): string {
  const recent = history.slice(-4).map((m) => `${m.role === "user" ? "当事人" : "卦师"}：${m.content}`).join("\n");
  return [
    "【账单卦案】",
    JSON.stringify(payload, null, 0),
    recent ? `\n【最近对话】\n${recent}` : "",
    `\n【当事人这次问】\n${question}`,
    "\n请用不超过 140 字回答，只引用卦案里的数字。",
  ].join("\n");
}
